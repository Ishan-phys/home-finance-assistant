def test_text_document_address_block_and_card_fingerprint() -> None:
    result = redactor().redact(axis_style())
    text = "\n".join(result.document.lines).upper()
    for private in ("MIRA", "KULKARNI", "LAKE VIEW", "411001", "8084", "TARA", "NAIR"):
        assert private not in text, private
    for keep in (
        "PAYMENT SUMMARY",
        "₹ -8,935.00",
        "03 OCT '26",
        "CASHBACK CREDIT AUG26-POS:435",
        "₹ 435.00 CREDIT",
    ):
        assert keep in text, keep
    assert result.report.fingerprint is not None
    # the fingerprint is stable for the same card, and differs for another
    again = redactor().redact(axis_style()).report.fingerprint
    assert again == result.report.fingerprint
    other = axis_style().map_text(lambda s: s.replace("8084", "9999"))
    assert redactor().redact(other).report.fingerprint != result.report.fingerprint


def test_tokens_are_stable_per_payee_and_distinct_across_payees() -> None:
    r = redactor(terms=())
    a1 = r.redact(
        Document.sheet([["UPI-TARA NAIR-x"], ["UPI-TARA NAIR-y"], ["UPI-BHAVESH-z"]])
    ).document
    t = [row[0] for row in a1.rows]
    tok = lambda s: s.split("-")[1]  # noqa: E731
    assert tok(t[0]) == tok(t[1]) and tok(t[0]) != tok(t[2])
    assert tok(t[0]).startswith("[PERSON:") and tok(t[0]).endswith("]")
    # a different salt gives different tokens: tokens cannot be linked across ledgers
    other = redactor(terms=(), salt=b"another-salt-0123456789abcdef-0123").redact(
        Document.sheet([["UPI-TARA NAIR-x"]])
    )
    assert tok(other.document.rows[0][0]) != tok(t[0])


def test_idempotent() -> None:
    r = redactor()
    once = r.redact(hdfc_style())
    twice = r.redact(once.document)
    assert twice.document == once.document
    assert twice.report.total == 0  # nothing left to find


def test_unlisted_neighbour_of_a_name_is_part_of_the_name_but_business_words_are_not() -> None:
    r = redactor(terms=())
    out = r.redact(Document.sheet([["UPI-ARJUN MEHTA-q"], ["MEHTA STORES pay"], ["Rahul Order"]]))
    first, second, third = (row[0] for row in out.document.rows)
    assert "ARJUN" not in first and "MEHTA" not in first
    assert "STORES" in second and "MEHTA" not in second  # a business word stays
    assert "Order" in third and "Rahul" not in third


