@pytest.mark.parametrize(
    ("narration", "kept"),
    [
        ("UPI-ARJUN K MEHTA-q1@oksbi-SBIN0001-1-UPI", "UPI-{}-"),
        ("UPIRET-MR T ARJUN ROYAL-q1@ybl-NESF0001-1-PAYMENT FROM PHONE", "UPIRET-{}-"),
        ("UPI-AUTOPAY-PRIYA VERMA-q1@okaxis-HDFC0001-1-EXEC", "UPI-AUTOPAY-{}-"),
        ("WDL TFR UPI/DR/402512345678/RAVI SHARMA K/YESB/paytm-r/UPI", "UPI/DR/{}/{}/"),
        ("IMPS-402512345678-ASHA GOEL P-HDFC-XXXXXXXX1234-IMPS TXN", "IMPS-{}-{}-"),
        ("NEFT CR-ICIC0000001-GITA MENON P-N123456789", "NEFT CR-ICIC0000001-"),
    ],
)
def test_the_other_partys_name_is_redacted_by_the_shape_of_the_narration(
    narration: str, kept: str
) -> None:
    out = redactor(terms=()).redact(Document.sheet([[narration]])).document.rows[0][0]
    assert "[PERSON:" in out
    for name in ("TIRUMALA", "VENKATI", "ARJUN", "PRIYA", "RAVI", "ASHA", "GITA"):
        assert name not in out.upper()
    assert out.upper().startswith(narration.split("-")[0].split("/")[0].upper()[:3])  # same rail


