def test_fails_closed() -> None:
    with pytest.raises(RedactionError):
        Redactor(RedactorConfig(salt=b""))
    r = redactor()

    def boom(self, text):  # type: ignore[no-untyped-def]
        raise ValueError("kaboom")

    import cfo.redact.redactor as module

    original = module._Run.scrub
    module._Run.scrub = boom  # type: ignore[method-assign]
    try:
        with pytest.raises(RedactionError, match="redaction failed"):
            r.redact(Document.sheet([["UPI-TARA NAIR"]]))
    finally:
        module._Run.scrub = original  # type: ignore[method-assign]


