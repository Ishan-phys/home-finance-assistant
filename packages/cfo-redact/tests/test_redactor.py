def test_a_name_split_by_a_fixed_width_wrap_is_still_caught() -> None:
    out = (
        redactor(terms=("Arjun Mehta", "Arjun", "Mehta"))
        .redact(Document.sheet([["DEP TFR   0011223344556 OF Mr. ARJU\n N  MEHTA AT 01234 PBB"]]))
        .document.rows[0][0]
    )
    assert "ARJU" not in out and "MEHTA" not in out and " N " not in out.split("Mr.")[1][:12]
