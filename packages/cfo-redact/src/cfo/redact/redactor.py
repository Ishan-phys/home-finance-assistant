# Where the other party's name sits in a UPI, IMPS or NEFT narration.
_PAYEE_RAILS = (
    re.compile(r"^(?P<pre>UPI(?:RET)?-(?:(?:AUTOPAY|MANDATE)-)?)(?P<payee>[^-]+?)\s*(?=-)", re.I),
    re.compile(r"^(?P<pre>(?:WDL TFR|DEP TFR)\s+UPI/(?:DR|CR)/[^/]+/)(?P<payee>[^/]+)(?=/)", re.I),
    re.compile(r"^(?P<pre>IMPS-\d+-)(?P<payee>[^-]+?)\s*(?=-)", re.I),
    re.compile(
        r"^(?P<pre>NEFT (?:CR|DR)-(?:[A-Z]{4}0[A-Z0-9]{6}-)?)(?P<payee>[^-]+?)\s*(?=-)", re.I
    ),
)


def looks_like_person(payee: str) -> bool:
    """Whether a payee field is probably an individual rather than a business.

    A business has a business word or a known brand, or starts with "the", or is one word. Two or
    three plain words, a title, or a lone initial read as a person's name."""
    words = [w.casefold() for w in re.findall(r"[A-Za-z]+", _TOKEN.sub(" ", payee))]
    if len(words) < 2 or len(words) > 4 or words[0] == "the":
        return False
    if words[0] in _TITLES:
        return True  # "MR T ARJUN ROYAL": a title outranks a business-sounding surname
    if any(w in _BUSINESS_WORDS or w in _BRANDS for w in words):
        return False
    return any(len(w) == 1 for w in words) or len(words) <= 3


_NOT_A_NAME = frozenset(
    """ltd limited pvt private stores store enterprises enterprise traders trading services
    service mart foods food restaurant hotel medical pharmacy electronics fashion mobiles
    jewellers jewelers bank bakery cafe sweets tea centre center agency agencies industries
    solutions technologies payment payments transfer upi imps neft rtgs to from for of at by
    and the mr mrs ms dr shri smt master miss refund order""".split()
)


def _norm(value: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s]", " ", value.casefold())).strip()


class Redactor:
    def __init__(self, config: RedactorConfig) -> None:
        if not config.salt:
            raise RedactionError("a salt is required")
        self._salt = config.salt
        self._card_statement = config.card_statement
        self._terms = sorted({t.strip() for t in config.terms if t.strip()}, key=len, reverse=True)
        self._term_words = {
            w.casefold() for t in self._terms for w in _WORD.findall(t) if len(w) >= 3
        }
        self._term_res = [re.compile(re.escape(t), re.IGNORECASE) for t in self._terms]

    # tokens -------------------------------------------------------------------------

    def token(self, cls: str, value: str) -> str:
        digest = hmac.new(self._salt, f"{cls}:{_norm(value)}".encode(), hashlib.sha256).hexdigest()
        return f"[{cls}:{digest[:4]}]"

    def fingerprint(self, value: str) -> str:
        key = re.sub(r"[^0-9a-z]", "", value.casefold())
        return hmac.new(self._salt, f"ACCT:{key}".encode(), hashlib.sha256).hexdigest()[:12]

    # public -------------------------------------------------------------------------

    def redact_text(self, text: str) -> str:
        """Redact one narration on its own. Used to prepare matching keys, never for storage."""
        return _Run(self).scrub(re.sub(r"\r?\n ?", "", text))

    def redact(self, doc: Document) -> RedactionResult:
        try:
            run = _Run(self)
            if doc.kind is DocumentKind.TEXT:
                out = run.text(doc)
            else:
                out = run.sheet(doc)
            return RedactionResult(out, RedactionReport(dict(run.counts), run.fingerprint))
        except RedactionError:
            raise
        except Exception as exc:  # fail closed: no partial, no fallback to raw text
            raise RedactionError(f"redaction failed: {type(exc).__name__}") from exc


class _Run:
    """One redaction pass over one document."""

    def __init__(self, r: Redactor) -> None:
        self.r = r
        self.counts: Counter[str] = Counter()
        self.fingerprint: str | None = None
        self.in_transactions = False  # set while the rows of a statement are being read

    def hit(self, cls: str, value: str) -> str:
        self.counts[cls] += 1
        return self.r.token(cls, value)

    # strings --------------------------------------------------------------------------

    def _payee(self, text: str) -> tuple[str, str | None]:
        """The other party's name, when the narration's structure says it is a person's. When the
        structure says it is a business, that payee is held back from the name lists (returned
        with a marker in its place) so a word like "Sagar" or "Sharma" cannot hide what it is."""
        for rail in _PAYEE_RAILS:
            m = rail.match(text)
            if m is None:
                continue
            payee = m.group("payee")
            if looks_like_person(payee):
                token = self.hit(PERSON, payee)
                return text[: m.start("payee")] + token + text[m.end("payee") :], None
            return text[: m.start("payee")] + _HELD + text[m.end("payee") :], payee
        return text, None

    def scrub(self, text: str) -> str:
        """Terms, the payee, patterns, then names, on one string."""
        for term_re in self.r._term_res:
            text = term_re.sub(lambda m: self.hit(PERSON, m.group()), text)
        text, held = self._payee(text)

        def master(m: re.Match[str]) -> str:
            kind = m.lastgroup
            if kind in ("keep", "date", "amount"):
                return m.group()
            if kind == "card" and self.fingerprint is None:
                self.fingerprint = self.r.fingerprint(m.group())
            cls = {
                "email": EMAIL,
                "pan": PAN,
                "vpa": VPA,
                "phone": PHONE,
                "card": ID,
                "digits": ID,
            }[kind or "digits"]
            return self.hit(cls, m.group())

        text = _MASTER.sub(master, text)
        if self._merchant_line(text):
            out = text  # the owner's terms already ran; the lists would only hide a merchant
        else:
            out = self._names(text)
        if held is not None:
            out = out.replace(_HELD, _MASTER.sub(master, held), 1)
        return out

    def _merchant_line(self, text: str) -> bool:
        """A card purchase, where a listed name is part of a shop's name, not a person."""
        return _POS_LINE.match(text) is not None or (
            self.r._card_statement and self.in_transactions
        )

    def _note_card(self, text: str) -> None:
        """A masked card number inside text about to be redacted still identifies the account."""
        card = re.search(r"\d{2,6}[Xx*]{2,}\d{2,4}", text)
        if card and self.fingerprint is None:
            self.fingerprint = self.r.fingerprint(card.group())

    def _names(self, text: str) -> str:
        """Names are replaced between tokens only, so an existing token is never touched."""
        parts = _TOKEN_SPLIT.split(text)
        return "".join(p if i % 2 else self._names_in(p) for i, p in enumerate(parts))

    def _names_in(self, text: str) -> str:
        words = list(_WORD.finditer(text))
        if not words:
            return text
        listed = [
            w.group().casefold() in NAMES or w.group().casefold() in self.r._term_words
            for w in words
        ]
        if not any(listed):
            return text
        # group consecutive listed words joined only by spaces or dots
        groups: list[list[int]] = []
        for i, is_name in enumerate(listed):
            if not is_name:
                continue
            if groups and re.fullmatch(
                r"[\s.]*", text[words[groups[-1][-1]].end() : words[i].start()]
            ):
                groups[-1].append(i)
            else:
                groups.append([i])
        pieces: list[str] = []
        cursor = 0
        for g in groups:
            lo, hi = g[0], g[-1]
            # One unlisted neighbour on each side is part of the name ("ARJUN MEHTA"),
            # but only next to a word from the bundled lists. A word the owner added as a term
            # (their own name, which may be an ordinary word) never drags its neighbours along.
            if any(words[k].group().casefold() in NAMES for k in g):
                if lo > 0 and self._neighbour(text, words, lo - 1, lo, listed):
                    lo -= 1
                if hi + 1 < len(words) and self._neighbour(text, words, hi + 1, hi, listed):
                    hi += 1
            start, end = words[lo].start(), words[hi].end()
            if start < cursor:
                continue
            pieces.append(text[cursor:start])
            pieces.append(self.hit(PERSON, text[start:end]))
            cursor = end
        pieces.append(text[cursor:])
        return "".join(pieces)

    @staticmethod
    def _neighbour(
        text: str, words: list[re.Match[str]], i: int, anchor: int, listed: list[bool]
    ) -> bool:
        a, b = sorted((i, anchor))
        gap = text[words[a].end() : words[b].start()]
        word = words[i].group()
        return (
            not listed[i]
            and re.fullmatch(r"[ ]+", gap) is not None
            and len(word) >= 3
            and word.casefold() not in _NOT_A_NAME
        )

    # sheets ---------------------------------------------------------------------------

    def sheet(self, doc: Document) -> Document:
        rows = [list(r) for r in doc.rows]
        zone = self._zone_end_sheet(rows)
        address_cells: set[tuple[int, int]] = set()
        for col in range(max((len(r) for r in rows), default=0)):
            column = [
                (str(r[col]) if col < len(r) and isinstance(r[col], str) else None)
                for r in rows[:zone]
            ]
            address_cells |= {(i, col) for i in self._address_rows(column)}
        id_columns: set[int] = set()
        for i, row in enumerate(rows):
            self.in_transactions = i >= zone
            for j in range(len(row)):
                if (i, j) in address_cells and isinstance(row[j], str):
                    self._note_card(row[j])
                    row[j] = self.hit(ADDRESS, row[j])
            self._label_row(row)
            for j, cell in enumerate(row):
                if isinstance(cell, str) and _norm(cell) in _ID_COLUMNS:
                    id_columns.add(j)
                elif (
                    j in id_columns
                    and cell is not None
                    and str(cell).strip()
                    and not _TOKEN.fullmatch(str(cell).strip())
                ):
                    row[j] = self.hit(ID, str(cell))
                    continue
                row[j] = self._cell(cell)
        return Document.sheet(rows)

    @staticmethod
    def _first_text(row: list[Any]) -> str | None:
        return next((c for c in row if isinstance(c, str) and c.strip()), None)

    def _zone_end_sheet(self, rows: list[list[Any]]) -> int:
        """Rows above the first one that looks like a transaction: a date and an amount."""
        for i, row in enumerate(rows):
            dated = any(
                isinstance(c, date | datetime) or (isinstance(c, str) and _is_date_like(c))
                for c in row
            )
            amount = any(
                isinstance(c, int | float)
                and not isinstance(c, bool)
                or (isinstance(c, str) and re.search(r"\d+\.\d{1,2}\s*$", c) is not None)
                for c in row
            )
            if dated and amount:
                return i
        return len(rows)

    @staticmethod
    def _is_label_cell(cell: Any) -> bool:
        if not isinstance(cell, str):
            return False
        if _label_key(cell) in _LABELS:
            return True
        m = _INLINE.match(cell)
        return bool(m and _label_key(m.group("label")) in _LABELS)

    def _label_row(self, row: list[Any]) -> None:
        """`Label | value` across cells, and `Label : value` within one cell. A label's values
        are the cells after it up to the next label."""
        j = 0
        while j < len(row):
            cell = row[j]
            if isinstance(cell, str):
                label = _label_key(cell)
                if label in _LABELS:
                    k = j + 1
                    while k < len(row) and not self._is_label_cell(row[k]):
                        value = row[k]
                        if (
                            value is not None
                            and str(value).strip()
                            and not _TOKEN.fullmatch(str(value))
                        ):
                            row[k] = self._labelled(label, str(value))
                        k += 1
                    j = k
                    continue
                m = _INLINE.match(cell)
                if m and _label_key(m.group("label")) in _LABELS:
                    label = _label_key(m.group("label"))
                    rest = f"  {m.group('rest')}" if m.group("rest") else ""
                    row[j] = (
                        f"{cell[: m.start('value')]}{self._labelled(label, m.group('value'))}{rest}"
                    )
            j += 1

    def _labelled(self, label: str, value: str) -> str:
        if _TOKEN.fullmatch(value.strip()):
            return value
        cls = _LABELS[label]
        if label in _FINGERPRINT_LABELS and self.fingerprint is None:
            self.fingerprint = self.r.fingerprint(value)
        return self.hit(cls, value)

    def _cell(self, cell: Any) -> Any:
        if not isinstance(cell, str):
            return cell  # typed numbers and dates are never personal details
        # Fixed-width exports wrap a narration mid-word ("ARJU\n N"); join it as the parser will,
        # or a name split across the wrap would escape the match.
        cell = re.sub(r"\r?\n ?", "", cell)
        if _PHONE_CELL.match(cell):
            return self.scrub(cell)
        if _PLAIN_NUMBER.match(cell):
            if re.fullmatch(r"\s*\d{10,}\s*", cell):
                return self.hit(ID, cell)  # a reference or account number, not an amount
            return cell  # a whole-cell number is an amount
        return self.scrub(cell)

    # text -----------------------------------------------------------------------------

    def text(self, doc: Document) -> Document:
        lines = list(doc.lines)
        zone = next(
            (i for i, line in enumerate(lines) if _TRANSACTION_LINE.search(line)), len(lines)
        )
        address = self._address_rows(lines[:zone])
        out: list[str] = []
        for i, line in enumerate(lines):
            self.in_transactions = i >= zone
            if i in address:
                self._note_card(line)
                out.append(self.hit(ADDRESS, line))
                continue
            if i < zone:
                m = _INLINE.match(line)
                if m and _label_key(m.group("label")) in _LABELS:
                    label = _label_key(m.group("label"))
                    rest = f"  {m.group('rest')}" if m.group("rest") else ""
                    line = (
                        f"{line[: m.start('value')]}{self._labelled(label, m.group('value'))}{rest}"
                    )
            out.append(self._cell(line) if not _is_amount_line(line) else self.scrub(line))
        return Document.text(out)

    # address blocks ---------------------------------------------------------------------

    def _address_rows(self, pieces: Sequence[str | None]) -> set[int]:
        """The lines around a postal pincode in the header: up to three before it, the pincode
        line itself, and a following all-capitals line such as a state."""
        found: set[int] = set()
        for i, piece in enumerate(pieces):
            pin = _PINCODE.search(piece) if piece is not None else None
            if (
                piece is None
                or pin is None
                or ":" in piece[: pin.start()]
                or len(re.findall(r"[A-Za-z]", piece)) < 3
            ):
                continue  # no pincode, or it sits after a label such as an account number
            found.add(i)
            j = i - 1
            while j >= 0 and i - j <= 3 and self._plain_line(pieces[j]):
                found.add(j)
                j -= 1
            nxt = pieces[i + 1] if i + 1 < len(pieces) else None
            if self._plain_line(nxt) and nxt is not None and nxt.upper() == nxt and len(nxt) <= 40:
                found.add(i + 1)
        return found

    @staticmethod
    def _plain_line(piece: str | None) -> bool:
        """A line of address-like text: not blank, not a token, not a label or heading, and
        without a colon, an amount, or a date."""
        if piece is None or not piece.strip() or _TOKEN.fullmatch(piece.strip()):
            return False
        if _label_key(piece) in _LABELS or _TITLE_WORDS.search(piece):
            return False  # a heading such as "Axis Bank Credit Card Monthly Statement"
        return (
            ":" not in piece
            and not _is_date_like(piece)
            and re.search(r"\d+\.\d{2}", piece) is None
        )


def _label_key(text: str) -> str:
    return re.sub(r"[\s.:]+$", "", re.sub(r"\s+", " ", text.strip().casefold()))


def _is_date_like(text: str) -> bool:
    return any(re.search(shape, text) for shape in _DATE_SHAPES[:3])


def _is_amount_line(line: str) -> bool:
    return bool(re.search(r"\d+\.\d{2}", line))


def redact_all(redactor: Redactor, docs: Iterable[Document]) -> list[RedactionResult]:
    return [redactor.redact(d) for d in docs]
