"""Redact personal details from a `Document` (spec 4.12.2).

Every hit becomes a pseudonym token `[CLASS:xxxx]`, where `xxxx` is the first four hex characters
of an HMAC of the normalized value under the ledger's salt. The same payee always gets the same
token and different payees get different ones, so deduplication and grouping keep working, and
a token cannot be turned back into the value. Redaction is idempotent: tokens are skipped.

What is protected and never touched: amounts, dates and times, the labels themselves, and any
typed numeric or date cell. What is found, in order: the ledger's terms, labelled values, an
address block, then patterns (email, PAN, mobile number, UPI handle, masked card, long digit
runs), then given names and surnames.
"""

from __future__ import annotations

import hashlib
import hmac
import re
from collections import Counter
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from datetime import date, datetime
from typing import Any

from cfo.doc import Document, DocumentKind
from cfo.redact.names import NAMES

PERSON, ADDRESS, EMAIL, PHONE, PAN, ID, VPA = (
    "PERSON",
    "ADDRESS",
    "EMAIL",
    "PHONE",
    "PAN",
    "ID",
    "VPA",
)


class RedactionError(Exception):
    """Redaction failed. The caller must reject the file and use no unredacted fallback."""


@dataclass(frozen=True, slots=True)
class RedactorConfig:
    salt: bytes
    terms: tuple[str, ...] = ()
    # A card statement's transaction lines are merchants, so the bundled name lists are not applied
    # to them ("Sagar Ratna" is a restaurant). The owner's own terms always are.
    card_statement: bool = False


@dataclass(frozen=True, slots=True)
class RedactionReport:
    """What was redacted, by class. Never the values."""

    counts: dict[str, int] = field(default_factory=dict)
    fingerprint: str | None = None  # of the card or account number, when the file has one

    @property
    def total(self) -> int:
        return sum(self.counts.values())


@dataclass(frozen=True, slots=True)
class RedactionResult:
    document: Document
    report: RedactionReport


